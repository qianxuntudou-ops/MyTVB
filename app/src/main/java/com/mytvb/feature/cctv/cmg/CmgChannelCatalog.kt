    /** 从 yangshipin 播放页 URL 提取 pid（非该形态返回 null）。 */
    fun pidFromUrl(url: String): String? {
        if (!url.contains("yangshipin.cn")) return null
        val match = Regex("[?&]pid=(\\d+)").find(url) ?: return null
        return match.groupValues[1]
    }

    /** pid 是否具备 CMG 原生直拉条件（表内有 cnlid）。 */
    fun isSupported(pid: String): Boolean = CNLID_BY_PID.containsKey(pid)

    fun cnlidOf(pid: String): String? = CNLID_BY_PID[pid]
